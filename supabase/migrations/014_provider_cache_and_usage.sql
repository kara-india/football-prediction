-- Shared provider snapshots and quota observations for the A1.5 on-demand feeds.
-- This table set contains public match data but is writable only by server-side service_role.

CREATE TABLE IF NOT EXISTS public.provider_request_cache (
    cache_key TEXT PRIMARY KEY,
    provider TEXT NOT NULL CHECK (provider IN ('football-data.org', 'the-odds-api')),
    payload JSONB NOT NULL,
    provider_metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    synced_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    expires_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_provider_request_cache_expiry
    ON public.provider_request_cache (expires_at);

CREATE TABLE IF NOT EXISTS public.provider_quota_snapshots (
    provider TEXT PRIMARY KEY CHECK (provider IN ('football-data.org', 'the-odds-api')),
    remote_used BIGINT,
    remote_remaining BIGINT,
    last_request_cost INTEGER,
    last_request_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.provider_request_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider TEXT NOT NULL CHECK (provider IN ('football-data.org', 'the-odds-api')),
    endpoint TEXT NOT NULL,
    requested_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    quota_cost INTEGER NOT NULL DEFAULT 0 CHECK (quota_cost >= 0),
    response_status INTEGER,
    remote_used BIGINT,
    remote_remaining BIGINT
);

CREATE INDEX IF NOT EXISTS idx_provider_request_logs_provider_time
    ON public.provider_request_logs (provider, requested_at DESC);

CREATE TABLE IF NOT EXISTS public.provider_request_locks (
    lock_key TEXT PRIMARY KEY,
    locked_until TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE OR REPLACE FUNCTION public.try_acquire_provider_request_lock(
    p_lock_key TEXT,
    p_lock_seconds INTEGER DEFAULT 30
)
RETURNS BOOLEAN
LANGUAGE plpgsql
SET search_path = pg_catalog, public
AS $$
DECLARE
    v_acquired BOOLEAN;
BEGIN
    INSERT INTO public.provider_request_locks (lock_key, locked_until, updated_at)
    VALUES (p_lock_key, NOW() + make_interval(secs => GREATEST(1, LEAST(p_lock_seconds, 60))), NOW())
    ON CONFLICT (lock_key) DO UPDATE
        SET locked_until = EXCLUDED.locked_until,
            updated_at = NOW()
        WHERE public.provider_request_locks.locked_until < NOW()
    RETURNING TRUE INTO v_acquired;

    RETURN COALESCE(v_acquired, FALSE);
END;
$$;

ALTER TABLE public.provider_request_cache ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.provider_quota_snapshots ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.provider_request_logs ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.provider_request_locks ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE public.provider_request_cache FROM anon, authenticated;
REVOKE ALL ON TABLE public.provider_quota_snapshots FROM anon, authenticated;
REVOKE ALL ON TABLE public.provider_request_logs FROM anon, authenticated;
REVOKE ALL ON TABLE public.provider_request_locks FROM anon, authenticated;

GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.provider_request_cache TO service_role;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.provider_quota_snapshots TO service_role;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.provider_request_logs TO service_role;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.provider_request_locks TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.provider_request_logs_id_seq TO service_role;

REVOKE ALL ON FUNCTION public.try_acquire_provider_request_lock(TEXT, INTEGER) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.try_acquire_provider_request_lock(TEXT, INTEGER) TO service_role;
